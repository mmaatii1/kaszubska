"""Build the self-hosted icon sprite and web-font subsets used by index.html.

    uv run --with fonttools --with brotli tools/build_assets.py

- Icon sprite, inlined at the end of index.html between the `icons:start` / `icons:end`
  markers: one <symbol> per Phosphor icon referenced anywhere in the file, including JS
  strings (`<i class="ph ph-NAME">` -> #r-NAME, `<i class="ph-bold ph-NAME">` -> #b-NAME).
  Inline because the HTML is served `no-cache`, so a changed icon can never be stale.
  Source: @phosphor-icons/core (MIT), pinned below.
- assets/fonts/*.woff2: Inter (variable wght 300-800, opsz pinned to 14) and
  Playfair Display regular/italic (variable wght 400-700), subset to Latin +
  Latin Extended-A (Polish) + the punctuation the page uses.
  Source: google/fonts (OFL, licence texts copied next to the fonts).

After adding an icon (`<i class="ph-bold ph-NAME" aria-hidden="true"><svg><use href="#b-NAME"></use></svg></i>`)
run `... tools/build_assets.py icons`; it rewrites the sprite block.
"""
import io
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HTML = ROOT / "index.html"
FONTS_OUT = ROOT / "assets" / "fonts"

PHOSPHOR = "https://unpkg.com/@phosphor-icons/core@2.1.1/assets"
GOOGLE_FONTS = "https://github.com/google/fonts/raw/main/ofl"
SPRITE_START, SPRITE_END = "<!-- icons:start -->", "<!-- icons:end -->"

UNICODES = (
    list(range(0x20, 0x7F))        # Basic Latin
    + list(range(0xA0, 0x100))     # Latin-1 (nbsp, ², ×, ó …)
    + list(range(0x100, 0x180))    # Latin Extended-A (ą ć ę ł ń ś ź ż)
    + list(range(0x2010, 0x2028))  # dashes, quotes „ ” ‘ ’, bullet, ellipsis
    + list(range(0x2030, 0x203B))  # per mille, ‹ ›
    + [0x2009, 0x202F, 0x20AC, 0x2122, 0x2190, 0x2191, 0x2192, 0x2193, 0x2212]
)

FONTS = [
    # (source file in google/fonts, output name, axis limits)
    ("inter/Inter%5Bopsz,wght%5D.ttf", "inter-var.woff2", {"opsz": 14, "wght": (300, 800)}),
    ("playfairdisplay/PlayfairDisplay%5Bwght%5D.ttf", "playfair-var.woff2", {"wght": (400, 700)}),
    ("playfairdisplay/PlayfairDisplay-Italic%5Bwght%5D.ttf", "playfair-italic-var.woff2", {"wght": (400, 700)}),
]
LICENCES = [("inter/OFL.txt", "OFL-Inter.txt"), ("playfairdisplay/OFL.txt", "OFL-PlayfairDisplay.txt")]


def fetch(url: str) -> bytes:
    with urllib.request.urlopen(url, timeout=60) as r:
        return r.read()


def used_icons(html: str) -> list[str]:
    ids = set()
    for weight, name in re.findall(r'class="(ph|ph-bold) ph-([a-z0-9-]+)', html):
        ids.add(("b-" if weight == "ph-bold" else "r-") + name)
    return sorted(ids)


def build_sprite() -> None:
    html = HTML.read_text(encoding="utf-8")
    symbols = []
    for icon_id in used_icons(html):
        weight, name = icon_id.split("-", 1)
        url = f"{PHOSPHOR}/bold/{name}-bold.svg" if weight == "b" else f"{PHOSPHOR}/regular/{name}.svg"
        svg = fetch(url).decode("utf-8")
        view_box = re.search(r'viewBox="([^"]+)"', svg).group(1)
        inner = re.sub(r"^.*?<svg[^>]*>|</svg>\s*$", "", svg, flags=re.S).strip()
        inner = re.sub(r"<rect[^>]*fill=\"none\"[^>]*/>", "", inner)  # Phosphor's empty bounding box
        symbols.append(f'<symbol id="{icon_id}" viewBox="{view_box}">{inner}</symbol>')
    block = (
        f"{SPRITE_START}\n"
        "<!-- Phosphor Icons 2.1.1 (MIT, https://phosphoricons.com); generated by tools/build_assets.py -->\n"
        '<svg xmlns="http://www.w3.org/2000/svg" style="display:none" aria-hidden="true">\n'
        + "\n".join(symbols) + f"\n</svg>\n{SPRITE_END}"
    )
    start, end = html.index(SPRITE_START), html.index(SPRITE_END) + len(SPRITE_END)
    HTML.write_text(html[:start] + block + html[end:], encoding="utf-8")
    print(f"index.html sprite: {len(symbols)} icons, {len(block)} bytes")


def build_fonts() -> None:
    from fontTools import subset
    from fontTools.ttLib import TTFont
    from fontTools.varLib import instancer

    FONTS_OUT.mkdir(parents=True, exist_ok=True)
    for src, out, limits in FONTS:
        font = TTFont(io.BytesIO(fetch(f"{GOOGLE_FONTS}/{src}")), lazy=False)
        font = instancer.instantiateVariableFont(font, limits)
        buf = io.BytesIO()
        font.save(buf)  # round-trip so the subsetter sees fully compiled tables
        font = TTFont(io.BytesIO(buf.getvalue()), lazy=False)
        opts = subset.Options()
        opts.flavor = "woff2"
        opts.layout_features = ["kern", "liga", "calt", "ccmp", "locl", "mark", "mkmk", "tnum", "lnum", "pnum"]
        opts.name_IDs = ["*"]
        opts.notdef_outline = True
        sub = subset.Subsetter(opts)
        sub.populate(unicodes=UNICODES)
        sub.subset(font)
        target = FONTS_OUT / out
        font.flavor = "woff2"
        font.save(target)
        print(f"{target.relative_to(ROOT)}: {target.stat().st_size} bytes")
    for src, out in LICENCES:
        (FONTS_OUT / out).write_bytes(fetch(f"{GOOGLE_FONTS}/{src}"))


if __name__ == "__main__":
    what = sys.argv[1:] or ["icons", "fonts"]
    if "icons" in what:
        build_sprite()
    if "fonts" in what:
        build_fonts()
